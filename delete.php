<?php

error_reporting(E_ALL);
ini_set('display_errors', 1);

session_start();


/*
|--------------------------------------------------------------------------
| ADMIN LOGIN CHECK
|--------------------------------------------------------------------------
*/

if (
    !isset($_SESSION["admin_logged_in"]) ||
    $_SESSION["admin_logged_in"] !== true
) {
    header("Location: login.php");
    exit;
}


/*
|--------------------------------------------------------------------------
| DATABASE
|--------------------------------------------------------------------------
*/

require_once "db.php";


/*
|--------------------------------------------------------------------------
| GET MESSAGE ID
|--------------------------------------------------------------------------
*/

$id = filter_input(
    INPUT_GET,
    "id",
    FILTER_VALIDATE_INT
);


if (!$id || $id <= 0) {

    header("Location: dashboard.php");

    exit;
}


/*
|--------------------------------------------------------------------------
| DELETE MESSAGE
|--------------------------------------------------------------------------
*/

$stmt = $conn->prepare(
    "DELETE FROM contact_messages WHERE id = ?"
);

$stmt->bind_param(
    "i",
    $id
);

$stmt->execute();


/*
|--------------------------------------------------------------------------
| CLOSE
|--------------------------------------------------------------------------
*/

$stmt->close();

$conn->close();


/*
|--------------------------------------------------------------------------
| BACK TO DASHBOARD
|--------------------------------------------------------------------------
*/

header(
    "Location: dashboard.php"
);

exit;

?>